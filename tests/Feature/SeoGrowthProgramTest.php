        ->and($body)->toContain("User-agent: OAI-SearchBot\nAllow: /")
        ->and($body)->toContain("User-agent: *\nAllow: /");
});

test('admins publish validated structured guides with hero media on R2', function () {
    Storage::fake('r2');
    config(['filesystems.media' => 'r2']);
    $admin = User::factory()->create();
    $role = Role::factory()->create(['name' => 'admin']);
    $admin->roles()->attach($role);
    $category = Category::factory()->create();

    $payload = [
        'title' => 'Choosing a safe charger',
        'slug' => 'choosing-a-safe-charger',
        'excerpt' => 'A concise charger buying guide for Sri Lankan shoppers.',
        'quick_answer' => 'Match the connector, wattage and supported charging protocol.',
        'sections' => [['heading' => 'Check compatibility', 'paragraphs' => ['Match both ends of the cable and the charging protocol.']]],
        'buying_checklist' => ['Confirm connector and wattage.'],
        'hero_image' => UploadedFile::fake()->image('charger.jpg', 1600, 900),
        'hero_image_alt' => 'Phone charger and cable comparison',
        'seo_title' => 'Choosing a Safe Phone Charger - ProDeals.lk',
        'seo_description' => 'Compare connector, wattage and fast-charging compatibility before buying a phone charger in Sri Lanka.',
        'primary_query' => 'phone charger types',
        'supporting_queries' => ['usb c charger sri lanka'],
        'trends_researched_at' => today()->toDateString(),
        'status' => 'published',
        'category_ids' => [$category->id],
    ];

    $this->actingAs($admin)->post(route('admin.guides.store'), $payload)->assertRedirect();

    $guide = Guide::query()->where('slug', 'choosing-a-safe-charger')->firstOrFail();
    expect($guide->hero_image_disk)->toBe('r2')
        ->and($guide->isPublished())->toBeTrue()
        ->and($guide->categories->first()->id)->toBe($category->id);
    Storage::disk('r2')->assertExists($guide->hero_image_path);
    $this->get(route('guides.show', $guide->slug))->assertOk();

    unset($payload['hero_image']);
    $payload['slug'] = 'choosing-a-safe-phone-charger';
    $this->actingAs($admin)->patch(route('admin.guides.update', $guide), $payload)->assertRedirect();
    $guide->refresh();
    $this->get('/guides/choosing-a-safe-charger?utm_source=legacy')
        ->assertRedirect('/guides/choosing-a-safe-phone-charger?utm_source=legacy')
        ->assertStatus(301);

    $this->actingAs($admin)->delete(route('admin.guides.destroy', $guide))->assertRedirect(route('admin.guides.index'));
    expect($guide->fresh()->trashed())->toBeTrue();

    $superAdminRole = Role::factory()->create(['name' => 'super_admin']);
    $admin->roles()->attach($superAdminRole);
    $this->actingAs($admin)->post(route('admin.guides.restore', $guide->id))->assertRedirect(route('admin.guides.index'));
    expect($guide->fresh()->trashed())->toBeFalse();
});

test('initial trends content seed is idempotent and preserves existing editorial copy', function () {
    foreach (['Food Mixers & Blenders', 'Rice Cookers', 'Electric Kettles', 'Power Adapters & Chargers', 'Storage & Data Transfer Cables'] as $name) {
        Category::factory()->create(['name' => $name]);
    }
    $blenders = Category::query()->where('name', 'Food Mixers & Blenders')->firstOrFail();
    $blenders->update(['seo_title' => 'Existing editor title']);
    $seller = SellerProfile::factory()->create(['status' => 'approved', 'about' => null]);
    Listing::factory()->for($seller)->for($blenders)->create();

    $this->artisan('seo:seed-growth-content')->assertSuccessful();
    $this->artisan('seo:seed-growth-content')->assertSuccessful();

    expect(Guide::query()->count())->toBe(5)
        ->and(Guide::query()->where('status', 'published')->count())->toBe(5)
        ->and(SeoRedirect::query()->where('source_path', '/shop')->where('destination_path', '/listings')->count())->toBe(1)
        ->and($blenders->fresh()->seo_title)->toBe('Existing editor title')
        ->and($blenders->fresh()->seo_focus_query)->toBe('blender price in sri lanka')
        ->and($blenders->fresh()->seo_intro)->toContain("\n\n")
        ->and($blenders->fresh()->seo_intro)->not->toContain('\n')
        ->and($seller->fresh()->about)->toContain('Browse products currently available');

    $archivedGuide = Guide::query()->firstOrFail();
    $archivedGuide->delete();
    $this->artisan('seo:seed-growth-content')->assertSuccessful();
    expect(Guide::withTrashed()->count())->toBe(5)
        ->and($archivedGuide->fresh()->trashed())->toBeTrue();
});
