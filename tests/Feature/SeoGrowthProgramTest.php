test('exact fallback redirects record hits and chains collapse to a terminal path', function () {
    $service = app(SeoRedirectService::class);
    $service->create(['source_path' => '/new-shop', 'destination_path' => '/listings', 'is_active' => true]);
    $service->create(['source_path' => '/old-shop/', 'destination_path' => '/new-shop', 'is_active' => true]);

    expect(SeoRedirect::query()->where('source_path', '/old-shop')->value('destination_path'))->toBe('/listings');

    $this->get('/old-shop')->assertRedirect('/listings')->assertStatus(301);
    $this->get('/old-shop/extra')->assertNotFound();

    $redirect = SeoRedirect::query()->where('source_path', '/old-shop')->firstOrFail();
    expect($redirect->fresh()->hit_count)->toBe(1)
        ->and($redirect->fresh()->last_hit_at)->not->toBeNull();
});

test('self redirects and redirect loops are rejected', function () {
    $service = app(SeoRedirectService::class);

    expect(fn () => $service->create(['source_path' => '/same', 'destination_path' => '/same/', 'is_active' => true]))
        ->toThrow(ValidationException::class);

    $service->create(['source_path' => '/a', 'destination_path' => '/b', 'is_active' => true]);

    expect(fn () => $service->create(['source_path' => '/b', 'destination_path' => '/a', 'is_active' => true]))
        ->toThrow(ValidationException::class);
});

test('administrators manage legacy redirects and super administrators restore archived records', function () {
    $admin = User::factory()->create();
    $adminRole = Role::factory()->create(['name' => 'admin']);
    $admin->roles()->attach($adminRole);

    $this->actingAs($admin)->post(route('admin.seo-redirects.store'), [
        'source_path' => '/legacy-sale',
        'destination_path' => '/listings',
        'is_active' => true,
    ])->assertRedirect(route('admin.seo-redirects.index'));

    $redirect = SeoRedirect::query()->where('source_path', '/legacy-sale')->firstOrFail();
    $this->actingAs($admin)->patch(route('admin.seo-redirects.update', $redirect), [
        'source_path' => '/legacy-sale',
        'destination_path' => '/guides',
        'is_active' => true,
    ])->assertRedirect(route('admin.seo-redirects.index'));
    $this->get('/legacy-sale')->assertRedirect('/guides')->assertStatus(301);

    $this->actingAs($admin)->delete(route('admin.seo-redirects.destroy', $redirect))->assertRedirect(route('admin.seo-redirects.index'));
    expect($redirect->fresh()->trashed())->toBeTrue();
    $this->actingAs($admin)->post(route('admin.seo-redirects.restore', $redirect->id))->assertForbidden();

    $superAdminRole = Role::factory()->create(['name' => 'super_admin']);
    $admin->roles()->attach($superAdminRole);
    $admin->unsetRelation('roles');
    $this->actingAs($admin)->post(route('admin.seo-redirects.restore', $redirect->id))->assertRedirect(route('admin.seo-redirects.index'));
    expect($redirect->fresh()->trashed())->toBeFalse();

    $this->actingAs($admin)->post(route('admin.seo-redirects.store'), [
        'source_path' => '/legacy-sale/',
        'destination_path' => '/listings',
        'is_active' => true,
    ])->assertSessionHasErrors('source_path');

    $this->actingAs($admin)->post(route('admin.seo-redirects.store'), [
        'source_path' => '/unsafe-external',
        'destination_path' => 'https://example.com',
        'is_active' => true,
    ])->assertSessionHasErrors('destination_path');
});

test('discovery responses use shared caching while the merchant feed remains live', function () {
    $sitemap = $this->get(route('sitemap.index'));
    $robots = $this->get(route('robots'));
    $merchant = $this->get(route('feeds.google_merchant'));

    foreach ([$sitemap, $robots] as $response) {
        $response->assertOk();
        expect($response->headers->get('Cache-Control'))
            ->toContain('public', 'max-age=300', 's-maxage=3600', 'stale-while-revalidate=86400');
        expect($response->headers->get('ETag'))->not->toBeNull();
    }

    expect($merchant->headers->get('Cache-Control'))->toContain('no-cache');
});

test('robots output has exactly one sitemap declaration and the intended crawler rules', function () {
    $body = $this->get(route('robots'))->assertOk()->getContent();

    expect(substr_count($body, 'Sitemap: '.route('sitemap.index')))->toBe(1)
