test('only published guides are public and included in their dedicated sitemap', function () {
    $category = Category::factory()->create(['name' => 'Blenders']);
    $listing = Listing::factory()->for($category)->create();
    ListingMedia::factory()->for($listing)->create();
    $published = Guide::factory()->published()->create([
        'title' => 'Safe <script>alert(1)</script> Blender Guide',
        'slug' => 'safe-blender-guide',
        'sections' => [['heading' => 'Choose safely', 'paragraphs' => ['Never render <script>alert(2)</script> as HTML.']]],
    ]);
    $published->categories()->attach($category, ['sort_order' => 0]);
    $draft = Guide::factory()->create(['slug' => 'private-draft-guide']);
    $future = Guide::factory()->create(['slug' => 'future-guide', 'status' => 'published', 'published_at' => now()->addDay()]);

    $response = $this->get(route('guides.show', $published->slug));

    $response->assertOk()
        ->assertDontSee('<script>alert(2)</script>', false)
        ->assertSee('"@type":"Article"', false)
        ->assertSee('prodeals-social-card.png', false)
        ->assertSee('"@type":"BreadcrumbList"', false)
        ->assertSee('name="robots" content="index,follow,max-image-preview:large"', false)
        ->assertInertia(fn ($page) => $page
            ->where('guide.title', $published->title)
            ->where('guide.sections.0.paragraphs.0', 'Never render <script>alert(2)</script> as HTML.')
            ->where('guide.categories.0.slug', $category->slug)
            ->where('relatedListings.0.slug', $listing->slug));

    $this->get(route('guides.show', $draft->slug))->assertNotFound();
    $this->get(route('guides.show', $future->slug))->assertNotFound();

    $this->get(route('sitemap.index'))
        ->assertOk()
        ->assertSee(route('sitemap.guides'), false);
    $this->get(route('sitemap.guides'))
        ->assertOk()
        ->assertSee(route('guides.show', $published->slug), false)
        ->assertDontSee($draft->slug, false)
        ->assertDontSee($future->slug, false);
});

test('guide category and product links are bidirectional and crawlable', function () {
    $category = Category::factory()->create(['seo_intro' => "First safe paragraph.\n\nSecond safe paragraph."]);
    $brand = Brand::factory()->create();
    $listing = Listing::factory()->for($category)->for($brand)->create();
    $guide = Guide::factory()->published()->create();
    $guide->categories()->attach($category, ['sort_order' => 0]);

    $this->get(route('categories.show', $category->slug))
        ->assertOk()
        ->assertInertia(fn ($page) => $page
            ->where('intro', "First safe paragraph.\n\nSecond safe paragraph.")
            ->where('relatedGuides.0.slug', (string) $guide->slug));

    $this->get(route('listings.show', $listing->slug))
        ->assertOk()
        ->assertInertia(fn ($page) => $page->where('relatedGuides.0.slug', (string) $guide->slug));

    $this->get(route('brands.show', $brand->slug))
        ->assertOk()
        ->assertInertia(fn ($page) => $page->where('relatedGuides.0.slug', (string) $guide->slug));
});

